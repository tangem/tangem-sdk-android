/**
 * Deserialized response from the Tangem card after `AttestWalletKeyTask`
 *
 * @property cardId          unique Tangem card ID number
 * @property salt            random salt generated by the card
 * @property walletSignature `challenge` and `salt` signed with the wallet private key
 * @property challenge       challenge, used to check wallet
 * @property cardSignature   confirmation signature of the wallet ownership. COS: 2.01+.
 * And a wallet's status for COS: 6+.
 * The signed public key is the attested one: the derived key, if a derivation path is passed.
 * ConfirmationMode.none   : No signature will be returned.
 * ConfirmationMode.static : Wallet's public key and wallet's status (COS 6+) signed with the card's private key.
 * ConfirmationMode.dynamic: Wallet's public key, wallet's status (COS 6+), `challenge`, and `publicKeySalt`,
 * signed with the card's private key.
 * @property publicKeySalt   optional random salt, generated by the card for `dynamic` `confirmationMode`. COS: 2.01+
 * @property walletStatus    Status of the wallet. COS v.6+
 * @property counter         counter of `AttestWalletKey` command executions. A very big value of this counter may
 * indicate a hacking attempts. COS: 2.01+
 */
@Suppress("LongParameterList")
@JsonClass(generateAdapter = true)
class AttestWalletKeyResponse(
    val cardId: String,
    val salt: ByteArray,
    val walletSignature: ByteArray,
    val challenge: ByteArray,
    val cardSignature: ByteArray?,
    val publicKeySalt: ByteArray?,
    val walletStatus: CardWallet.Status?,
    internal val counter: Int?,
) : CommandResponse

/**
 * This task proves that the wallet private key from the card corresponds to the wallet public key.
 * Standard challenge/response scheme is used.
 * @property publicKey: Seed public key of the wallet to check
 * @property derivationPath: Optional derivation path of the wallet. COS v. 4.28 and higher,

 * @property confirmationMode: Additional confirmation of the wallet ownership.  The card will return the `cardSignature` (the attested wallet's public key — the derived one, if a derivation path is passed — signed by the card's private key)  in response.  COS: 2.01+.
 */
class AttestWalletKeyTask(
    private val publicKey: ByteArray,
    private val derivationPath: DerivationPath? = null,
    challenge: ByteArray? = null,
    private val confirmationMode: ConfirmationMode = ConfirmationMode.Dynamic,
) : Command<AttestWalletKeyResponse>() {

    private val challenge = challenge ?: CryptoUtils.generateRandomBytes(16)

    override fun performPreCheck(card: Card): TangemError? {
        val error = card.assertWalletsAccess()
        if (error != null) {
            return error
        }

        val wallet = card.wallet(publicKey).guard {
            return TangemSdkError.WalletNotFound()
        }

        if (derivationPath != null) {
            when {
                card.firmwareVersion < FirmwareVersion.HDWalletAvailable -> {
                    return TangemSdkError.NotSupportedFirmwareVersion()
                }
                !wallet.curve.supportsDerivation() -> {
                    return TangemSdkError.UnsupportedCurve()
                }
                !card.settings.isHDWalletAllowed -> {
                    return TangemSdkError.HDWalletDisabled()
                }
            }
        }

        return null
    }

    override fun run(session: CardSession, callback: CompletionCallback<AttestWalletKeyResponse>) {
        if (derivationPath != null) {
            val derivationCommand =
                DeriveWalletPublicKeyTask(walletPublicKey = publicKey, derivationPath = derivationPath)
            derivationCommand.run(session) { result ->
                when (result) {
                    is CompletionResult.Success -> {
                        transceiveAttestation(session, callback)
                    }
                    is CompletionResult.Failure -> {
                        callback(CompletionResult.Failure(result.error))
                    }
                }
            }
        } else {
            transceiveAttestation(session, callback)
        }
    }

    private fun transceiveAttestation(session: CardSession, callback: CompletionCallback<AttestWalletKeyResponse>) {
        super.run(session) { result ->
            when (result) {
                is CompletionResult.Success -> {
                    val checkWalletResponse = result.data
                    val card = session.environment.card
                    val wallet = card?.wallet(publicKey)
                    if (wallet == null) {
                        callback(CompletionResult.Failure(TangemSdkError.CardError()))
                        return@run
                    }

                    try {
                        val walletPublicKey = getPublicKey(wallet)
                        val isWalletSignatureValid = verifyWalletSignature(
                            response = checkWalletResponse,
                            wallet = wallet,
                            walletPublicKey = walletPublicKey,
                        )
                        val isCardSignatureValid = verifyCardSignature(
                            response = checkWalletResponse,
                            cardPublicKey = card.cardPublicKey,
                            firmwareVersion = card.firmwareVersion,
                            walletPublicKey = walletPublicKey,
                        )
                        if (isWalletSignatureValid && isCardSignatureValid) {
                            callback(CompletionResult.Success(checkWalletResponse))
                        } else {
                            callback(CompletionResult.Failure(TangemSdkError.CardVerificationFailed()))
                        }
                    } catch (error: TangemSdkError) {
                        callback(CompletionResult.Failure(error))
                    }
                }
                is CompletionResult.Failure -> callback(result)
            }
        }
    }

    override fun serialize(environment: SessionEnvironment): CommandApdu {
        val card = environment.card ?: throw TangemSdkError.MissingPreflightRead()
        val walletIndex = card.wallet(publicKey)?.index ?: throw TangemSdkError.WalletNotFound()

        val builder = createTlvBuilder(environment.legacyMode)

        builder.append(TlvTag.Challenge, challenge)
        builder.append(TlvTag.WalletIndex, walletIndex)
        if (shouldAddPin(environment.accessCode, card.firmwareVersion)) {
            builder.append(TlvTag.Pin, environment.accessCode.value)
        }
        if (card.firmwareVersion < FirmwareVersion.v8) {
            builder.append(TlvTag.CardId, environment.card?.cardId)
        }

        // Otherwise, static confirmation will fail with the "invalidParams" error.
        if (card.firmwareVersion >= FirmwareVersion.WalletOwnershipConfirmationAvailable) {
            when (confirmationMode) {
                ConfirmationMode.None -> {}
                ConfirmationMode.Static -> builder.append(TlvTag.PublicKeyChallenge, byteArrayOf())
                ConfirmationMode.Dynamic -> builder.append(TlvTag.PublicKeyChallenge, challenge)
            }
        }

        if (derivationPath != null) {
            builder.append(TlvTag.WalletHDPath, derivationPath)
        }

        return CommandApdu(Instruction.AttestWalletKey, builder.serialize())
    }

    override fun deserialize(environment: SessionEnvironment, apdu: ResponseApdu): AttestWalletKeyResponse {
        val decoder = createTlvDecoder(environment, apdu)
        return AttestWalletKeyResponse(
            cardId = decoder.decode(TlvTag.CardId),
            salt = decoder.decode(TlvTag.Salt),
            walletSignature = decoder.decode(TlvTag.WalletSignature),
            challenge = challenge,
            cardSignature = decoder.decodeOptional(TlvTag.CardSignature),
            publicKeySalt = decoder.decodeOptional(TlvTag.PublicKeySalt),
            walletStatus = decoder.decodeOptional(TlvTag.Status),
            counter = decoder.decodeOptional(TlvTag.CheckWalletCounter),
        )
    }

    private fun verifyWalletSignature(
        response: AttestWalletKeyResponse,
        wallet: CardWallet,
        walletPublicKey: ByteArray,
    ): Boolean {
        // Impossible case because of precheck
        val currentWalletPublicKey = wallet.publicKey
            ?: throw TangemSdkError.WalletUnavailableBackupRequired()

        if (!currentWalletPublicKey.contentEquals(publicKey)) {
            return false
        }

        val signingPublicKey = if (derivationPath != null) {
            val derivedKey = wallet.derivedKeys[derivationPath] ?: run {
                throw TangemSdkError.WalletNotFound()
            }
            derivedKey.publicKey
        } else {
            currentWalletPublicKey
        }

        return CryptoUtils.verify(
            publicKey = signingPublicKey,
            message = challenge + response.salt,
            signature = response.walletSignature,
            curve = wallet.curve,
        )
    }

    internal fun verifyCardSignature(
        response: AttestWalletKeyResponse,
        cardPublicKey: ByteArray,
        firmwareVersion: FirmwareVersion,
        walletPublicKey: ByteArray,
    ): Boolean {
        val cardSignature = response.cardSignature
        if (cardSignature == null) {
            // The card signature is requested only on COS: 2.01+ when a confirmation mode other than `None` is used
            // (see the matching gate in `serialize`). When it was requested but the card returned no `CardSignature`
            // TLV, fail closed instead of accepting the response — otherwise an emulated card or a tampered response
            // could pass wallet-ownership verification by simply omitting the signature.
            val isCardSignatureExpected = confirmationMode != ConfirmationMode.None &&
                firmwareVersion >= FirmwareVersion.WalletOwnershipConfirmationAvailable
            return !isCardSignatureExpected
        }

        // If dynamic confirmation was requested, the response must contain `publicKeySalt`. If it is absent,
        // the signature covers a static message without the challenge — a previously recorded static
        // signature would pass verification (downgrade to static). Fail closed.
        if (confirmationMode == ConfirmationMode.Dynamic && response.publicKeySalt == null) {
            return false
        }

        // Dynamic verification
        var message = walletPublicKey
        if (response.publicKeySalt != null) message += challenge + response.publicKeySalt
        // The card signs (and transmits, see TLV TAG_Status length 01) walletStatus as a single
        // byte, so the verification message must append that one byte — not the 4-byte big-endian
        // Int.toByteArray() default, which never matches the card signature on COS 6+.
        if (response.walletStatus != null) message += response.walletStatus.code.toByte()

        return CryptoUtils.verify(
            publicKey = cardPublicKey,
            message = message,
            signature = cardSignature,
            curve = EllipticCurve.Secp256k1,
        )
    }

    private fun getPublicKey(wallet: CardWallet): ByteArray {
        return if (derivationPath != null) {
            val derivedKey = wallet.derivedKeys[derivationPath]
                ?: throw TangemSdkError.WalletNotFound()
            derivedKey.publicKey
        } else {
            wallet.publicKey ?: throw TangemSdkError.WalletUnavailableBackupRequired()
        }
    }

    enum class ConfirmationMode {
        None,
        Static,
        Dynamic,
    }
}